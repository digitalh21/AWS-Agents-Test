"use client";

import { useState } from "react";
import { Download, Gauge, Shuffle, SlidersHorizontal, UserPlus, X } from "lucide-react";
import { toast } from "sonner";
import { Button } from "@/components/ui/button";
import { Input, Label, NativeSelect } from "@/components/ui/field";
import { Sheet } from "@/components/ui/dialog";
import { LEAD_STATUSES, STATUS_META } from "@/lib/rbac";
import { num } from "@/lib/utils";

export type BulkAction = "assign" | "status" | "pool" | "fields" | "export";

/** Whitelisted keys for bulk field updates (mirrors /api/leads/bulk op=fields). */
export const BULK_FIELD_KEYS = [
  "websiteStatus", "serviceStatus", "statusService", "callStatus", "city", "cityKeyword",
  "nicheCategory", "leadStatus", "competitorName", "email", "opensAt", "title",
];

/**
 * Bulk Actions Bar shown above lead tables when rows are selected.
 * Agents never see this component — it is only rendered on staff tables.
 */
export function BulkActionsBar({
  selectedIds,
  agents,
  onClear,
  onDone,
  onAssign,
  onStatus,
  onPool,
  onFields,
}: {
  selectedIds: number[];
  agents: Array<{ id: string; name: string; role: string }>;
  onClear: () => void;
  onDone: () => void;
  onAssign: (agentId: string) => Promise<void>;
  onStatus: (status: string) => Promise<void>;
  onPool: () => Promise<void>;
  onFields: (fields: Record<string, string>) => Promise<void>;
}) {
  const [dialog, setDialog] = useState<BulkAction | null>(null);
  const [agentId, setAgentId] = useState("");
  const [status, setStatus] = useState<string>("NEW");
  const [fieldRows, setFieldRows] = useState<Array<{ k: string; v: string }>>([{ k: "websiteStatus", v: "" }]);
  const [busy, setBusy] = useState(false);
  const count = selectedIds.length;

  async function run() {
    if (!dialog) return;
    setBusy(true);
    try {
      if (dialog === "assign") {
        if (!agentId) throw new Error("Pick an agent");
        await onAssign(agentId);
        toast.success(`${count} lead(s) assigned`);
      } else if (dialog === "status") {
        await onStatus(status);
        toast.success(`${count} lead(s) moved to ${STATUS_META[status]?.label ?? status}`);
      } else if (dialog === "pool") {
        await onPool();
        toast.success(`${count} lead(s) returned to the Pool (status preserved)`);
      } else if (dialog === "fields") {
        const fields: Record<string, string> = {};
        for (const row of fieldRows) if (row.k && row.v.trim() !== "") fields[row.k] = row.v.trim();
        if (Object.keys(fields).length === 0) throw new Error("Set at least one field value");
        await onFields(fields);
        toast.success(`${count} lead(s) updated: ${Object.keys(fields).join(", ")}`);
      } else if (dialog === "export") {
        exportCsv();
      }
      setDialog(null);
      onDone();
    } catch (e) {
      toast.error(e instanceof Error ? e.message : "Bulk action failed");
    } finally {
      setBusy(false);
    }
  }

  function exportCsv() {
    toast.info(`Preparing CSV for ${count} lead(s)…`);
    // CSV is generated by the caller (it owns the row data)
    window.dispatchEvent(new CustomEvent("bulk-export", { detail: selectedIds }));
  }

  if (count === 0) return null;

  return (
    <>
      <div className="sticky top-0 z-20 flex flex-wrap items-center gap-2 rounded-xl border border-blue-200 bg-blue-50 p-2 shadow-sm">
        <span className="flex h-7 min-w-7 items-center justify-center rounded-full bg-blue-600 px-2 text-xs font-bold text-white">
          {count}
        </span>
        <span className="mr-1 text-xs font-semibold text-blue-900">selected</span>

        <Button size="xs" variant="secondary" onClick={() => setDialog("assign")}>
          <UserPlus className="h-3 w-3" /> Bulk Assign
        </Button>
        <Button size="xs" variant="secondary" onClick={() => setDialog("status")}>
          <Gauge className="h-3 w-3" /> Bulk Status
        </Button>
        <Button size="xs" variant="outline" onClick={() => setDialog("pool")}>
          <Shuffle className="h-3 w-3" /> Remove Assignment
        </Button>
        <Button size="xs" variant="outline" onClick={() => setDialog("fields")}>
          <SlidersHorizontal className="h-3 w-3" /> Update Fields
        </Button>
        <Button size="xs" variant="outline" onClick={() => exportCsv()}>
          <Download className="h-3 w-3" /> Bulk Export
        </Button>
        <Button size="xs" variant="ghost" className="ml-auto" onClick={onClear}>
          <X className="h-3 w-3" /> Clear
        </Button>
      </div>

      <Sheet
        open={Boolean(dialog)}
        onOpenChange={(v) => !v && setDialog(null)}
        title={
          dialog === "assign"
            ? `Assign ${count} lead(s)`
            : dialog === "status"
              ? `Change status for ${count} lead(s)`
              : dialog === "pool"
                ? `Remove assignment for ${count} lead(s)`
                : dialog === "fields"
                  ? `Update fields on ${count} lead(s)`
                : "Bulk action"
        }
        description={
          dialog === "pool"
            ? "The agent is cleared but the pipeline status is preserved, so the lead lands in the right Pool column."
            : undefined
        }
        footer={
          <div className="flex gap-2">
            <Button variant="ghost" className="flex-1" onClick={() => setDialog(null)}>
              Cancel
            </Button>
            <Button
              className="flex-1"
              disabled={
                busy ||
                (dialog === "assign" && !agentId) ||
                (dialog === "status" && !status)
              }
              onClick={() => void run()}
            >
              Apply to {count} lead{count === 1 ? "" : "s"}
            </Button>
          </div>
        }
      >
        <div className="space-y-2">
          {dialog === "assign" ? (
            <div className="space-y-1">
              <Label>Assign to agent</Label>
              <NativeSelect value={agentId} onChange={(e) => setAgentId(e.target.value)}>
                <option value="">— select agent —</option>
                {agents.map((a) => (
                  <option key={a.id} value={a.id}>
                    {a.name}
                  </option>
                ))}
              </NativeSelect>
            </div>
          ) : null}

          {dialog === "status" ? (
            <div className="space-y-1">
              <Label>Pipeline status</Label>
              <NativeSelect value={status} onChange={(e) => setStatus(e.target.value)}>
                {LEAD_STATUSES.filter((s) => s !== "ARCHIVED").map((s) => (
                  <option key={s} value={s}>
                    {STATUS_META[s].label}
                  </option>
                ))}
              </NativeSelect>
            </div>
          ) : null}

          {dialog === "fields" ? (
            <div className="space-y-2">
              <p className="text-[11px] text-muted-foreground">
                Overwrite these fields on ALL {count} selected lead(s). Each change is written to the leads&apos; history
                timelines (management-visible).
              </p>
              {fieldRows.map((row, i) => (
                <div key={i} className="flex gap-2">
                  <NativeSelect
                    value={row.k}
                    onChange={(e) => setFieldRows((rs) => rs.map((r, j) => (j === i ? { ...r, k: e.target.value } : r)))}
                  >
                    {BULK_FIELD_KEYS.map((k) => (
                      <option key={k} value={k}>
                        {k.replace(/([A-Z])/g, " $1").toLowerCase()}
                      </option>
                    ))}
                  </NativeSelect>
                  <Input
                    value={row.v}
                    onChange={(e) => setFieldRows((rs) => rs.map((r, j) => (j === i ? { ...r, v: e.target.value } : r)))}
                    placeholder="new value"
                  />
                  {fieldRows.length > 1 ? (
                    <Button size="sm" variant="ghost" onClick={() => setFieldRows((rs) => rs.filter((_, j) => j !== i))}>
                      <X className="h-3.5 w-3.5" />
                    </Button>
                  ) : null}
                </div>
              ))}
              <Button size="xs" variant="outline" onClick={() => setFieldRows((rs) => [...rs, { k: BULK_FIELD_KEYS[0]!, v: "" }])}>
                + Add field
              </Button>
            </div>
          ) : null}

          {dialog === "pool" ? (
            <div className="rounded-lg bg-stone-50 p-2.5 text-[11px] text-stone-700">
              <p className="font-semibold">Pool</p>
              <p className="mt-0.5">
                Assignment state and pipeline status are independent — these leads keep their current status
                (e.g. “No Response”) but their <em>Assigned To</em> becomes <strong>Pool</strong>.
              </p>
            </div>
          ) : null}

          {dialog === "export" ? (
            <p className="text-xs text-muted-foreground">A CSV of the {count} selected lead(s) will be generated.</p>
          ) : null}

          <p className="text-[10px] text-muted-foreground">
            Bulk operations are management-only. Telecalling agents have zero delete and zero bulk permissions.
          </p>
        </div>
      </Sheet>
    </>
  );
}

export function bulkSummary(ids: number[]) {
  return `${num(ids.length)} selected`;
}
